import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset, skipping bad lines and using the 'python' engine for robustness
# Trying latin1 encoding as a common solution for CSV parsing issues
try:
    df = pd.read_csv('/content/zomato.csv', on_bad_lines='skip', engine='python', encoding='latin1')
except Exception as e:
    print(f"Error loading CSV with latin1 encoding: {e}. Trying utf-8...")
    df = pd.read_csv('/content/zomato.csv', on_bad_lines='skip', engine='python', encoding='utf-8')


print("First 5 rows of the DataFrame:")
display(df.head())

print("\nDataFrame Information:")
display(df.info())

print("\nDescriptive Statistics:")
display(df.describe())

"""### Data Cleaning for 'rate' Column"""

# Clean the 'rate' column: remove '/5', replace 'New' with 0, convert to float, and fill NaNs with the mean.
# This ensures the 'rate' column is numeric and can be used for analysis.

# Convert 'rate' to string to handle mixed types and 'New' values consistently
df['rate'] = df['rate'].astype(str)

# Remove '/5' from the rate string and replace 'New' with an empty string temporarily
df['rate'] = df['rate'].str.replace('/5', '', regex=False).str.replace('New', '', regex=False)

# Convert to numeric, coercing errors to NaN
df['rate'] = pd.to_numeric(df['rate'], errors='coerce')

# Fill NaN values with the mean of the 'rate' column
df['rate'].fillna(df['rate'].mean(), inplace=True)

print("\n'rate' column after cleaning and filling NaNs:")
display(df[['rate']].head())
print(f"Mean rate after cleaning: {df['rate'].mean():.2f}")

"""### Visualizing Key Distributions and Categorical Features"""

plt.figure(figsize=(10, 6))
sns.histplot(df['rate'], bins=20, kde=True)
plt.title('Distribution of Restaurant Ratings')
plt.xlabel('Rating (out of 5)')
plt.ylabel('Number of Restaurants')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

plt.figure(figsize=(10, 6))
sns.histplot(df['votes'], bins=50, kde=True)
plt.title('Distribution of Number of Votes')
plt.xlabel('Number of Votes')
plt.ylabel('Number of Restaurants')
plt.grid(axis='y', linestyle='--', alpha=0.7)
plt.show()

fig, axes = plt.subplots(1, 2, figsize=(14, 6))

sns.countplot(x='online_order', data=df, ax=axes[0], palette='viridis', hue='online_order', legend=False)
axes[0].set_title('Online Order Availability')
axes[0].set_xlabel('Online Order')
axes[0].set_ylabel('Count')

sns.countplot(x='book_table', data=df, ax=axes[1], palette='magma', hue='book_table', legend=False)
axes[1].set_title('Table Booking Availability')
axes[1].set_xlabel('Book Table')
axes[1].set_ylabel('Count')

plt.tight_layout()
plt.show()

"""### Top 10 Restaurants by Number of Votes"""

top_10_restaurants_by_votes = df.sort_values(by='votes', ascending=False).head(10)
print("Top 10 Restaurants with the Highest Number of Votes:")
display(top_10_restaurants_by_votes[['name', 'votes', 'rate']])